#!/usr/bin/env python3
"""Writes the generated part of DesignKit from the reference source.

Input:  .local-dependencies/bitwarden-clients (support/fetch-reference-source.fish)
Output: Sources/DesignKit/Generated/*.swift and Sources/DesignKit/Resources/*

Colours, localization, Inter and illustrations retain their source attribution.
HonkPass interface icons use the native SF Symbols mapping in Symbols.swift.
"""
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / ".local-dependencies" / "bitwarden-clients"
TARGET = ROOT / "Sources" / "DesignKit"
REFERENCE = "bitwarden/clients, tag desktop-v2026.10.4"
HEADER = f"// Generated by support/generate-design-kit.py from {REFERENCE}. Do not edit.\n"
LOCALES = json.loads((TARGET / "Resources/Locales/languages.json").read_text())
SWIFT_KEYWORDS = set("""associatedtype class deinit enum extension fileprivate func import init inout internal let open
operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue
default defer do else fallthrough for guard if in repeat return throw switch where while Any as await false is nil self Self
super throws true try""".split())


def fail(message):
    sys.exit(f"generate-design-kit: {message}")


def block(text, selector):
    """The declarations of one top-level CSS rule."""
    start = text.index(selector + " {")
    depth, index = 0, text.index("{", start)
    opening = index
    while True:
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[opening + 1:index]
        index += 1


def declarations(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    return {name: " ".join(value.split()) for name, value in re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", css)}


def parse_colour(value):
    """A CSS colour as (r, g, b, a) with 0-255 channels, or None when the value is no colour."""
    value = value.strip()
    match = re.fullmatch(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", value)
    if match:
        rgb = match.group(1)
        alpha = int(match.group(2), 16) if match.group(2) else 255
        return (int(rgb[0:2], 16), int(rgb[2:4], 16), int(rgb[4:6], 16), alpha)
    match = re.fullmatch(r"#([0-9a-fA-F])([0-9a-fA-F])([0-9a-fA-F])", value)
    if match:
        return tuple(int(c * 2, 16) for c in match.groups()) + (255,)
    match = re.fullmatch(r"(\d+) (\d+) (\d+)", value)
    if match:
        return tuple(int(c) for c in match.groups()) + (255,)
    match = re.fullmatch(r"rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)", value)
    if match:
        alpha = match.group(4)
        if alpha is None:
            a = 255
        elif alpha.endswith("%"):
            a = round(float(alpha[:-1]) * 2.55)
        else:
            a = round(float(alpha) * 255)
        return (int(match.group(1)), int(match.group(2)), int(match.group(3)), a)
    return None


def resolve(name, table, depth=0):
    """Follows var() references, also inside rgba(), to a colour."""
    if name not in table or depth > 8:
        return None
    value = table[name]
    match = re.fullmatch(r"var\((--[\w-]+)\)", value)
    if match:
        return resolve(match.group(1), table, depth + 1)
    for _ in range(8):
        inner = re.search(r"var\((--[\w-]+)\)", value)
        if not inner:
            break
        if inner.group(1) not in table:
            return None
        value = value.replace(inner.group(0), table[inner.group(1)])
    return parse_colour(value)


def swift_name(css_name, prefix):
    words = css_name[len(prefix):].split("-")
    name = words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:])
    if not name or name[0].isdigit():
        name = "n" + name
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def generate_colours():
    theme = (SOURCE / "libs/components/src/tw-theme.css").read_text()
    light = declarations(block(theme, ":root"))
    dark = dict(light)
    dark.update(declarations(block(theme, ".theme_dark")))
    lines = [HEADER, "// The CSS variables `--color-*` of libs/components/src/tw-theme.css, light and dark.\n",
             "public extension ThemeColor {"]
    count = 0
    for css_name in light:
        if not css_name.startswith("--color-") or css_name.endswith("-rgb"):
            continue
        l, d = resolve(css_name, light), resolve(css_name, dark)
        if l is None or d is None:
            continue
        lines.append("    /// `%s`" % css_name)
        lines.append("    static let %s = ThemeColor(light: 0x%02X%02X%02X%02X, dark: 0x%02X%02X%02X%02X)"
                     % ((swift_name(css_name, "--color-"),) + l + d))
        count += 1
    lines.append("}")
    (TARGET / "Generated" / "Colors.generated.swift").write_text("\n".join(lines) + "\n")
    return count


ILLUSTRATIONS = {
    "vault": "vault.icon.ts",
    "no-results": "no-results.ts",
    "item-types": "item-types.ts",
    "empty-trash": "empty-trash.ts",
    "favorites": "favorites.icon.ts",
    "two-factor-auth-authenticator": "two-factor-auth-authenticator.icon.ts",
    "two-factor-auth-webauthn": "two-factor-auth-webauthn.icon.ts",
    "email-code-sent": "email-code-sent.icon.ts",
    "no-credentials": "no-credentials.icon.ts",
    "no-send": "no-send.icon.ts",
}
CARD_BRANDS = ["visa", "mastercard", "amex", "discover", "diners_club", "jcb", "maestro", "union_pay", "ru_pay"]


def generate_illustrations():
    """The SVG illustrations, once for each appearance, with the theme colours written in."""
    theme = (SOURCE / "libs/components/src/tw-theme.css").read_text()
    light = declarations(block(theme, ":root"))
    dark = dict(light)
    dark.update(declarations(block(theme, ".theme_dark")))
    target = TARGET / "Resources" / "Illustrations"
    target.mkdir(parents=True, exist_ok=True)
    for name, file in ILLUSTRATIONS.items():
        source = (SOURCE / "libs/assets/src/svg/svgs" / file).read_text()
        match = re.search(r"svg`\s*(<svg.*?</svg>)\s*`", source, flags=re.S)
        if not match:
            fail(f"no SVG in {file}")
        for appearance, table in (("light", light), ("dark", dark)):
            def paint(class_match):
                attributes = []
                for css_class in class_match.group(1).split():
                    kind = re.fullmatch(r"tw-(fill|stroke)-([\w-]+)", css_class)
                    colour = resolve("--color-" + kind.group(2), table) if kind else None
                    if colour is None:
                        fail(f"{file}: no colour for class {css_class}")
                    attributes.append('%s="#%02X%02X%02X"' % ((kind.group(1),) + colour[:3]))
                return " ".join(attributes)
            svg = re.sub(r'class="([^"]*)"', paint, match.group(1))
            (target / f"{name}-{appearance}.svg").write_text(svg + "\n")
    return len(ILLUSTRATIONS)


def copy_card_brands():
    """The pictures of card brands: libs/angular/src/billing/images/cards, light and dark."""
    target = TARGET / "Resources" / "Cards"
    target.mkdir(parents=True, exist_ok=True)
    count = 0
    for brand in CARD_BRANDS:
        for appearance in ("light", "dark"):
            source = SOURCE / "libs/angular/src/billing/images/cards" / f"{brand}-{appearance}.png"
            if source.exists():
                shutil.copyfile(source, target / source.name)
                count += 1
    return count


def copy_resources():
    resources = TARGET / "Resources"
    (resources / "Locales").mkdir(parents=True, exist_ok=True)
    (resources / "Fonts").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(SOURCE / "libs/components/src/webfonts/inter.woff2", resources / "Fonts" / "inter.woff2")
    # Interface symbols come from macOS. Do not restore the legacy icon font.
    for name in ("bwi-font.ttf", "honkpass-icons.ttf"):
        (resources / "Fonts" / name).unlink(missing_ok=True)
    (TARGET / "Generated" / "Icons.generated.swift").unlink(missing_ok=True)
    desktop_locales = SOURCE / "apps/desktop/src/locales"
    browser_locales = SOURCE / "apps/browser/src/_locales"
    desktop_en = json.loads((desktop_locales / "en/messages.json").read_text())
    browser_en = json.loads((browser_locales / "en/messages.json").read_text())
    keys = 0
    for locale in LOCALES:
        directory = locale.replace("-", "_")
        # Reused desktop texts take precedence over browser-extension fallback texts.
        # Original HonkPass wording stays in the separate honkpass-*.json resources.
        browser = browser_locales / directory / "messages.json"
        messages = json.loads(browser.read_text()) if browser.is_file() else {}
        desktop = json.loads((desktop_locales / directory / "messages.json").read_text())
        for key, entry in desktop.items():
            # Some desktop catalogs ship English where the browser already translated the same phrase.
            if (not locale.startswith("en") and key in messages
                    and entry["message"] == desktop_en.get(key, {}).get("message") == browser_en.get(key, {}).get("message")
                    and messages[key]["message"] != entry["message"]):
                continue
            messages[key] = entry
        # The texts of the AutoFill extension of the desktop app, which has its own file and
        # only in English: `"key" = "text";`
        strings = SOURCE / "apps/desktop/macos/autofill-extension" / f"{locale}.lproj" / "Localizable.strings"
        if strings.exists():
            for key, text in re.findall(r'^"([^"]+)"\s*=\s*"((?:[^"\\]|\\.)*)";', strings.read_text(), re.MULTILINE):
                messages.setdefault(key, {"message": text})
        # Only what the lookup needs: the text and the names of its placeholders.
        compact = {}
        for key, entry in messages.items():
            item = {"m": entry["message"]}
            placeholders = {name.lower(): value["content"] for name, value in entry.get("placeholders", {}).items()}
            if placeholders:
                item["p"] = placeholders
            compact[key] = item
        (resources / "Locales" / f"{locale}.json").write_text(
            json.dumps(compact, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n")
        keys = max(keys, len(compact))
    return keys


def main():
    if not (SOURCE / "libs/components/src/tw-theme.css").exists() or not (SOURCE / "apps/browser/src/_locales").exists():
        fail("the reference source is missing or lacks the browser extension; run: make reference-source")
    (TARGET / "Generated").mkdir(parents=True, exist_ok=True)
    colours = generate_colours()
    keys = copy_resources()
    illustrations = generate_illustrations()
    copy_card_brands()
    print(f"DesignKit: {colours} colours, native symbols, {keys} texts in {len(LOCALES)} languages, "
          f"{illustrations} illustrations, 1 font.")


main()
