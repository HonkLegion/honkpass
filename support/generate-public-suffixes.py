#!/usr/bin/env python3
"""Writes Sources/VaultModel/Resources/public-suffixes.txt from the public suffix list.

Input:  the copy of the list that the pinned Bitwarden SDK is built with
        (.local-dependencies/bitwarden-cargo/.../public-suffix/public_suffix_list.dat, there after
        `make prepare-sdk`). The SDK checks the domains of passkeys with it; PassVault uses the
        same revision to find the base domain of a website (PLAN.md, M3, step 4).
Output: the rules of the list, ICANN and private, one on a line, without its comments.
Run:    python3 -I support/generate-public-suffixes.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "Sources/VaultModel/Resources/public-suffixes.txt"


def main():
    sources = sorted((ROOT / ".local-dependencies/bitwarden-cargo").glob("git/checkouts/passkey-rs-*/*/public-suffix/public_suffix_list.dat"))
    if not sources:
        sys.exit("The public suffix list of the SDK is missing; run: make prepare-sdk")
    lines = sources[-1].read_text(encoding="utf-8").splitlines()
    version = next((line[3:].strip() for line in lines if line.startswith("// VERSION:")), "VERSION: unknown")
    rules = []
    for line in lines:
        # A rule ends at the first white space; a line that starts with "//" is a comment.
        rule = line.split()[0] if line.strip() else ""
        if rule and not rule.startswith("//"):
            rules.append(rule.lower())
    header = [
        "// The rules of the Public Suffix List (https://publicsuffix.org/list/), ICANN and private.",
        "// The list is subject to the terms of the Mozilla Public License, v. 2.0: https://mozilla.org/MPL/2.0/",
        f"// {version}. Generated by support/generate-public-suffixes.py; do not edit.",
    ]
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(header + rules) + "\n", encoding="utf-8")
    print(f"VaultModel: {len(rules)} public suffix rules ({version}).")


main()
